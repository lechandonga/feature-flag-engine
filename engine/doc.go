// Package engine 实现一个本地可配置的特性开关评估引擎。
//
// 核心保证：
//   - 稳定分桶：同一用户在任意评估顺序、进程重启、规则重排后落入同一分组；
//   - 快照隔离：后台刷新原子替换不可变配置快照，评估永不观察到中间状态；
//   - 失败降级：配置被拒绝或刷新失败时继续使用最近一次有效配置；
//   - 前置依赖：依赖缺失 / 环 / 自相矛盾在配置加载阶段被拒绝并给出可区分原因；
//   - 多版本：所有 schema 版本经同一入口归一化，未知字段忽略、非法/缺省取值处理一致；
//   - 归因解耦：异步上报 + 窗口去重，上报失败或延迟不影响评估。
